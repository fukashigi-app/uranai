/**
 * 生年月日占い（v2）の文章。3種類の中で最も本格的な占いとして、落ち着いた口調でそろえる。
 * 性格は断定せず「〜の傾向があります」「〜しやすいタイプ」程度にとどめる。
 *
 * ■ 特徴の差し込みは「意味の種類」ごとに分ける
 *   持ち味の名詞句（「見返りを求めない慈しみ」など）を何にでも差し込むと、
 *   「慈しみが冴える」「構想を形にする力を、誰かに頼ることに使う」のような不自然な文になる。
 *   そこで星座・誕生数の特徴を次の5種類に分け、文章の型の側も「その種類に合う言い回し」だけを使う。
 *
 *   act     行動   … 動詞で終わる句。「{…Act}こと」の形で使う
 *   mind    考え方 … 「〜視点・〜見方・〜目・〜発想・〜力」などで終わる名詞句。「冴える・役立つ・生かす」と組み合わせる
 *   people  対人   … 動詞で終わる句。「{…People}こと」の形で使う
 *   feel    気持ち … 「〜気持ち・〜思い・〜心・〜感」で終わる名詞句。「大切にする・素直になる・満たされる」と組み合わせる
 *   express 表現   … 動詞で終わる句。「{…Express}こと」「{…Express}ように」「{…Express}あなた」の形で使う
 *
 *   差し込み名は {lpAct} {lpMind} {lpPeople} {lpFeel} {lpExpress}（誕生数）と {signAct} … {signExpress}（星座）。
 *   持ち味の名詞句（quality）は「あなたの基本タイプ」の紹介文でだけ使う。
 *   組み合わせで不自然になりやすい「今日のテーマ」の本文は、誕生数のグループ×今日のナンバーごとの完成文にしている。
 *   同じ結果の中で同じ種類の特徴は2回使わない（birthday-fortune.ts で管理）。
 *
 * その他の差し込み: {sign}=星座名 / {lp}=誕生数 / {pd}=今日のナンバー / {keyword}=今日のテーマ / {month}=誕生月 / {monthMotif}=誕生月の気配
 */

